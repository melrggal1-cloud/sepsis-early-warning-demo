"""Small interactive view of the synthetic demo unit.

    streamlit run app/dashboard.py
"""
import json
from pathlib import Path

import pandas as pd
import streamlit as st

OUT = Path(__file__).resolve().parents[1] / "outputs"
st.set_page_config(page_title="Sepsis early warning (synthetic demo)", layout="wide")
st.error("Research demonstration on SYNTHETIC data. Not a medical device. Not for clinical use.")

if not (OUT / "demo_unit.json").exists():
    st.info("Run `python run_demo.py` first.")
    st.stop()

unit = json.loads((OUT / "demo_unit.json").read_text())
metrics = json.loads((OUT / "metrics.json").read_text())
threshold = unit["threshold"]

st.title("ICU overview")
st.caption(f"Alert threshold {threshold:.2f} · every patient below is generated by a random number generator")
table = pd.DataFrame([{
    "Bed": b["bed"], "Patient": b["label"], "Risk (next 6 h)": b["risk_now"],
    "6 h ago": b["risk_6h_ago"], "Alert": "ALERT" if b["alert"] else "",
    "Driving organ system": b["driving_organ"] if b["risk_now"] >= threshold / 2 else "-",
} for b in unit["beds"]])
st.dataframe(table, hide_index=True, use_container_width=True)

choice = st.selectbox("Open a patient", [b["bed"] for b in unit["beds"]])
bed = next(b for b in unit["beds"] if b["bed"] == choice)
left, right = st.columns(2)
with left:
    st.subheader(f"{bed['bed']} · {bed['label']}")
    risk = pd.DataFrame({"Risk": bed["risk_last_24h"],
                         "Threshold": threshold},
                        index=range(-len(bed["risk_last_24h"]) + 1, 1))
    risk.index.name = "Hours before now"
    st.line_chart(risk)
with right:
    st.subheader("Why")
    st.bar_chart(pd.Series(bed["organ_contributions"], name="Contribution to the score"))
    st.write(f"Largest contribution: **{bed['driving_organ']}**")
    st.dataframe(pd.DataFrame(bed["driver_values"]).T, use_container_width=True)

st.divider()
st.subheader("Unit report (synthetic test patients)")
m = metrics["causal_features"]
a, b, c, d = st.columns(4)
a.metric("False alerts / 100 patient-days", f"{m['false_alerts_per_100_patient_days']:.0f}")
b.metric("Sepsis patients warned before onset", f"{100 * m['share_of_sepsis_patients_warned_before_onset']:.0f} %")
c.metric("Median warning time", f"{m['median_warning_hours']:.0f} h")
d.metric("Hourly AUROC", f"{m['hourly_auroc']:.2f}")
st.caption(metrics["WARNING"])
